#!/usr/bin/env python3
"""U2: how far does vctrl jump per phase decision, against C2? Open loop, SPICE.

    gen_u2.py        # writes decks/U2_c2.spice

U1 measured the charge-pump current into an ideal voltage source. That
overstates the switching spikes: the source supplies whatever charge the
pump's internal nodes demand, where the real 16 fF C2 node has to share it.
U2 replaces the source with the real tiny_pll_loop_filter, so the step on
vctrl at each decision is the real one, and adds copies of
tiny_pll_loop_filter_cap2 in parallel to test a larger C2.

One copy per configuration, each: ideal clock (CML levels, fixed offset) ->
cml_pd -> tiny_pll_charge_pump (+ own bias_gen) -> loop filter (+ extra C2).
All decisions have the same sign at a fixed offset, so vctrl ramps; the run is
kept to 25 UI (~8 decisions) so it stays near the 0.79 V lock point.
u2_analyze.py reports the fast step at each decision (the part a bigger C2
should shrink) and the total change per decision.
Pure stdlib (../../../CLAUDE.md).
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "cml"))
sys.path.insert(0, os.path.join(HERE, "..", "power"))
from gen_cml import prbs7, pwl, NETDIR, UI  # noqa: E402
import gen_power as gp  # noqa: E402

# (label, PD, offset, extra cap2 copies): extra=0 is today's C2 (16 fF)
C2_CONFIGS = [("cml_c2x1", "cml", -0.03, 0), ("cml_c2x2", "cml", -0.03, 1),
              ("cml_c2x4", "cml", -0.03, 3), ("frz_c2x1", "frozen", -0.03, 0)]
# U2_cx: static-CMOS XOR variants of the CML PD (cx_cells.inc), today's C2
CX_CONFIGS = [("cml", "cml", -0.03, 0), ("cx6", "cx6", -0.03, 0),
              ("cx3", "cx3", -0.03, 0), ("frozen", "frozen", -0.03, 0)]
NBITS = 25
VLOCK = 0.79


def deck(CONFIGS, name):
    bits = prbs7(NBITS + 20)[20:]          # skip the all-ones seed run
    tstop = NBITS * UI
    lines, saves, ics = [], [], []
    for k, (label, pd, ph, extra) in enumerate(CONFIGS):
        if pd != "frozen":
            lo, hi, tr = 1.03, 1.43, 200e-12
        else:
            lo, hi, tr = 0.0, 1.8, 80e-12
        td = 0.5 * UI + ph * UI - tr / 2
        pw = UI / 2 - tr
        lines.append(f"* {label}: {pd} PD, offset {ph:+.2f} UI, C2 x{extra + 1}")
        lines.append(f"Vck{k} ck{k} 0 PULSE({lo} {hi} {td:.4e} {tr} {tr} {pw:.4e} {UI})")
        if pd != "frozen":
            cell = "cml_pd" if pd == "cml" else f"cml_pd_{pd}"
            lines.append(f"Vckb{k} ckb{k} 0 PULSE({hi} {lo} {td:.4e} {tr} {tr} {pw:.4e} {UI})")
            lines.append(f"xpd{k} vdd 0 dn{k} up{k} ck{k} ckb{k} dp dm vbias {cell}")
        else:
            lines.append(f"xinv{k} vdd 0 ck{k} ckb{k} single_inverter")
            lines.append(f"xpd{k} vdd 0 dn{k} up{k} ck{k} dp ckb{k} dm vbias alexander_phase_detector")
        lines.append(f"xbg{k} 0 0 vdd vdd bn{k} vdd 0 bp{k} tiny_pll_bias_gen")
        lines.append(f"xcp{k} vdd vdd 0 0 vc{k} up{k} dn{k} bn{k} bp{k} tiny_pll_charge_pump")
        lines.append(f"xlf{k} 0 0 vdd vdd vc{k} tiny_pll_loop_filter")
        for e in range(extra):
            lines.append(f"xc2e{k}_{e} 0 0 vdd vdd vc{k} 0 tiny_pll_loop_filter_cap2")
        ics += [f"v(vc{k})={VLOCK}", f"v(xlf{k}.cap_plus)={VLOCK}"]
        saves += [f"v(vc{k})", f"v(xlf{k}.cap_plus)"]
    names = " ".join(f"vc{k} c1_{k}" for k in range(len(CONFIGS)))
    lets = "\n".join(f"  let vc{k} = v(vc{k})\n  let c1_{k} = v(xlf{k}.cap_plus)"
                     for k in range(len(CONFIGS)))
    return f"""* GENERATED by gen_u2.py -- do not edit.
* U2: vctrl step per decision vs C2, open loop, real loop filter
* configs {' '.join(c[0] for c in CONFIGS)}
* bits {''.join(map(str, bits))}
.lib {gp.PDK}/sky130A/libs.tech/ngspice/sky130.lib.spice tt
.include {gp.PDK}/sky130A/libs.ref/sky130_fd_sc_hd/spice/sky130_fd_sc_hd.spice
.include {NETDIR}/frozen.inc
.include {NETDIR}/cml_cells.inc
.include {HERE}/cx_cells.inc
.options method=gear reltol=0.001
Vdd vdd 0 1.8
Vb vbias 0 0.9
Vd vd 0 PWL({pwl(bits, 0.15)})
Ep dp 0 vol='1.3 + v(vd)'
Em dm 0 vol='1.3 - v(vd)'
{chr(10).join(lines)}
.ic {' '.join(ics)}
.control
  save {' '.join(saves)}
  tran 2p {tstop:.4e}
{lets}
  set filetype=ascii
  write {name}.raw {names}
.endc
.end
"""


if __name__ == "__main__":
    os.makedirs(os.path.join(HERE, "decks"), exist_ok=True)
    for cfg, name in ((C2_CONFIGS, "U2_c2"), (CX_CONFIGS, "U2_cx")):
        with open(os.path.join(HERE, "decks", f"{name}.spice"), "w") as fh:
            fh.write(deck(cfg, name))
    print("wrote decks/U2_c2.spice decks/U2_cx.spice")
