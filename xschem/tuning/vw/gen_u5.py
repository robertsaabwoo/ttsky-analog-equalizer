#!/usr/bin/env python3
"""U5: survey of other glitch / spike / kickback paths in the frozen design.

    gen_u5.py        # writes decks/U5_survey.spice   (~3 min, tt / 27 C / 1.8 V)

Independent copies in one deck, each isolating one path:
  A  frozen PD at +0.10 UI (decisions of the other sign): does the OTHER
     XOR output (down = Q5 xor B) glitch the way up did in U3?
  B  frozen PD at -0.03 UI, pump output held at 0.65 V
  C  frozen PD at -0.03 UI, pump output held at 0.95 V
     (B/C vs U4's 0.79 V: the pump's switches sit at the drain side of the
     current sources, so src_n/src_p charge-share with vctrl at every switch
     event; how much depends on vctrl)
  D  frozen PD at -0.03 UI with its eight latch tails fed from vbias through
     500 ohm (a TT analog pad path) instead of an ideal 0.9 V: kickback onto
     the shared vbias pin, which also biases the CTLE
  E  the real CTLE, driven through the 500 ohm / 5 pF pad model, loaded by a
     frozen PD (ideal clock)
  F  an identical CTLE with no PD load -- E minus F is the PD's sampling
     kickback onto the CTLE output
Pure stdlib (../../../CLAUDE.md).
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "cml"))
sys.path.insert(0, os.path.join(HERE, "..", "power"))
from gen_cml import prbs7, pwl, NETDIR, UI  # noqa: E402
import gen_power as gp  # noqa: E402

NB = 30


def clk(name, ph, tr=80e-12):
    td = 0.5 * UI + ph * UI - tr / 2
    pw = UI / 2 - tr
    return f"V{name} {name} 0 PULSE(0 1.8 {td:.4e} {tr} {tr} {pw:.4e} {UI})"


def pd_cp(k, ck, data, vb, vsrc):
    """frozen PD (probe version) + its own bias_gen + pump into Vvc{k}."""
    return [f"xinv{k} vdd 0 {ck} {ck}b single_inverter",
            f"xpd{k} vdd 0 dn{k} up{k} {ck} {data[0]} {ck}b {data[1]} {vb} bp{k} bm{k} "
            f"q5p{k} q5m{k} q2p{k} q2m{k} alex_probe",
            f"xbg{k} 0 0 vdd vdd bn{k} vdd 0 bpp{k} tiny_pll_bias_gen",
            f"xcp{k} vdd vdd 0 0 vc{k} up{k} dn{k} bn{k} bpp{k} tiny_pll_charge_pump",
            f"Vvc{k} vc{k} 0 {vsrc}"]


def deck():
    bits = prbs7(NB + 20)[20:]
    L = ["Vdd vdd 0 1.8", "Vb vbias 0 0.9",
         f"Vd vd 0 PWL({pwl(bits, 0.15)})",
         "Ep dp 0 vol='1.3 + v(vd)'", "Em dm 0 vol='1.3 - v(vd)'",
         clk("cka", 0.10), clk("ckm", -0.03)]
    L += ["* A: +0.10 UI"] + pd_cp("A", "cka", ("dp", "dm"), "vbias", 0.79)
    L += ["* B: vctrl 0.65 V"] + pd_cp("B", "ckm", ("dp", "dm"), "vbias", 0.65)
    L += ["* C: vctrl 0.95 V"] + pd_cp("C", "ckm", ("dp", "dm"), "vbias", 0.95)
    L += ["* D: vbias through a 500 ohm pad path", "RbD vbias vbD 500"] + \
        pd_cp("D", "ckm", ("dp", "dm"), "vbD", 0.79)
    # E/F: CTLE input through the pad model, as in the chain decks
    L += ["* E/F: CTLE output kickback",
          f"Vs ds 0 PWL({pwl(bits, 1.0)})",
          "Edinp dinp 0 vol='0.9 + 0.1*v(ds)'", "Edinm dinm 0 vol='0.9 - 0.1*v(ds)'",
          "Rpp dinp cinp 500", "Cpp cinp 0 5p", "Rpm dinm cinm 500", "Cpm cinm 0 5p",
          "xctE eqEp eqEm cinp cinm vdd 0 vbias CTLE",
          "xctF eqFp eqFm cinp cinm vdd 0 vbias CTLE"]
    L += pd_cp("E", "ckm", ("eqEp", "eqEm"), "vbias", 0.79)
    saves = ["v(upA)", "v(dnA)", "i(VvcA)", "i(VvcB)", "i(VvcC)", "v(upD)", "v(dnD)",
             "i(VvcD)", "v(vbD)", "v(eqEp)", "v(eqEm)", "v(eqFp)", "v(eqFm)", "v(ckm)"]
    lets = ["  let iA = -i(VvcA)", "  let iB = -i(VvcB)", "  let iC = -i(VvcC)",
            "  let iD = -i(VvcD)"]
    names = "upA dnA iA iB iC upD dnD iD vbD eqEp eqEm eqFp eqFm ckm"
    return f"""* GENERATED by gen_u5.py -- do not edit.
* U5: glitch / spike / kickback survey, frozen design, tt 27C 1.8V
* bits {''.join(map(str, bits))}
.lib {gp.PDK}/sky130A/libs.tech/ngspice/sky130.lib.spice tt
.include {gp.PDK}/sky130A/libs.ref/sky130_fd_sc_hd/spice/sky130_fd_sc_hd.spice
.include {NETDIR}/frozen.inc
.include {HERE}/alex_probe.inc
.options method=gear reltol=0.001
{chr(10).join(L)}
.control
  save {' '.join(saves)}
  tran 5p {NB * UI:.4e}
{chr(10).join(lets)}
  set filetype=ascii
  write U5_survey.raw {names}
.endc
.end
"""


if __name__ == "__main__":
    os.makedirs(os.path.join(HERE, "decks"), exist_ok=True)
    with open(os.path.join(HERE, "decks", "U5_survey.spice"), "w") as fh:
        fh.write(deck())
    print("wrote decks/U5_survey.spice")
