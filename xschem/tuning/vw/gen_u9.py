#!/usr/bin/env python3
"""U9: which stage of the CML PD breaks at sf/ff (U8: one-sided characteristic)?

    gen_u9.py        # writes decks/U9_<corner>.spice for tt_27C (reference) and sf_27C

CML PD at an early clock offset (-0.05 UI, where U8 reads ~0 net charge at sf
but +1.4 at tt), pump into an ideal 0.79 V source. Saves every internal stage:
latch outputs (q5, q2, b), CML XOR outputs (u/ub -> up, dn/dnb -> down), the
cml2cmos mirror outputs (x8.y for down, x9.y for up) and the CMOS outputs.
Pure stdlib (../../../CLAUDE.md).
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "cml"))
sys.path.insert(0, os.path.join(HERE, "..", "power"))
sys.path.insert(0, os.path.join(HERE, "..", "pvt"))
from gen_cml import prbs7, pwl, NETDIR, UI  # noqa: E402
import gen_power as gp  # noqa: E402
from gen_pvt import corner_block  # noqa: E402

NODES = ["q5", "q5b", "q2", "q2b", "b", "bb", "u", "ub", "dn", "dnb", "x8.y", "x9.y", "x8.z", "x9.z"]
# cx3 on cml_bias: latch outputs, converter outputs (a5, a2, bp) and their mirror nodes
NODES_CX = ["q5", "q5b", "q2", "q2b", "b", "bb", "a5", "a2", "bp", "xc5.y", "xc2.y", "xcb.y"]
NB, PH = 30, -0.05


def deck(mos, temp, cx=False):
    nodes = NODES_CX if cx else NODES
    bits = prbs7(NB + 20)[20:]
    tr = 200e-12
    td = 0.5 * UI + PH * UI - tr / 2
    pw = UI / 2 - tr
    lets = "\n".join(f"  let {n.replace('.', '_')} = v(xpd0.{n})" for n in nodes)
    names = " ".join(n.replace(".", "_") for n in nodes)
    return f"""* GENERATED by gen_u9.py -- do not edit.
* U9 ({mos} {temp}C): CML PD internals at {PH:+.2f} UI
* bits {''.join(map(str, bits))}
{corner_block(mos, "typ", temp)}
.include {gp.PDK}/sky130A/libs.ref/sky130_fd_sc_hd/spice/sky130_fd_sc_hd.spice
.include {NETDIR}/frozen.inc
.include {NETDIR}/cml_cells.inc
.include {HERE}/cx_cells.inc
.include {HERE}/bias/cml_bias.inc
.options method=gear reltol=0.001
Vdd vdd 0 1.8
Vb vbias 0 0.9
Vd vd 0 PWL({pwl(bits, 0.15)})
Ep dp 0 vol='1.3 + v(vd)'
Em dm 0 vol='1.3 - v(vd)'
Vck0 ck0 0 PULSE(1.03 1.43 {td:.4e} {tr} {tr} {pw:.4e} {UI})
Vckb0 ckb0 0 PULSE(1.43 1.03 {td:.4e} {tr} {tr} {pw:.4e} {UI})
{"xref vdd 0 vbn cml_bias" if cx else ""}
xpd0 vdd 0 dn0 up0 ck0 ckb0 dp dm {"vbn cml_pd_cx3" if cx else "vbias cml_pd"}
xbg0 0 0 vdd vdd bn0 vdd 0 bp0 tiny_pll_bias_gen
xcp0 vdd vdd 0 0 vc0 up0 dn0 bn0 bp0 tiny_pll_charge_pump
Vvc0 vc0 0 0.79
.control
  save {' '.join(f'v(xpd0.{n})' for n in nodes)} v(up0) v(dn0) i(Vvc0)
  tran 5p {NB * UI:.4e}
{lets}
  let i0 = -i(Vvc0)
  set filetype=ascii
  write U9{'_cx' if cx else ''}_{mos}_{temp}C.raw {names} up0 dn0 i0
.endc
.end
"""


if __name__ == "__main__":
    os.makedirs(os.path.join(HERE, "decks"), exist_ok=True)
    for m, t in (("tt", 27), ("sf", 27)):
        with open(os.path.join(HERE, "decks", f"U9_{m}_{t}C.spice"), "w") as fh:
            fh.write(deck(m, t))
    for m, t in (("tt", 27), ("sf", 125)):
        with open(os.path.join(HERE, "decks", f"U9_cx_{m}_{t}C.spice"), "w") as fh:
            fh.write(deck(m, t, cx=True))
    print("wrote decks/U9_{tt_27C,sf_27C}.spice and decks/U9_cx_{tt_27C,sf_125C}.spice")
