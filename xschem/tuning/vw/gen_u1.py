#!/usr/bin/env python3
"""U1: phase-detector LOOP DELAY unit bench -- frozen PD vs CML PD, no loop.

    gen_u1.py            # writes decks/U1_frozen.spice and decks/U1_cml.spice

Each deck holds one copy per clock-phase offset of
    ideal clock -> phase detector -> real tiny_pll_charge_pump (+ its own bias_gen)
with the charge-pump output held at the lock point (0.79 V) by an ideal source,
whose current is the measured output. Data is PRBS7 at CTLE-output levels
(300 mV diff pp, CM 1.3 V). u1_analyze.py then reports, per offset, the delay
from each data transition to the start of the charge-pump current pulse, and
the charge each decision delivers. That delay sits inside the loop: the loop
model (bbloop.py) says ~1 UI more of it is enough to explain the CML design's
wander.

Clocks are what each PD sees in its own design:
  frozen: rclk+ full rail (inverter_buffer output), rclk- made from it by the
          design's own single_inverter (so the 33/61 % duty skew is included);
  cml:    ck/ckb at the weakened diff_amp_inv's output levels, 1.03-1.43 V (C2).
Runs in a few minutes. Pure stdlib (../../../CLAUDE.md).
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "cml"))
sys.path.insert(0, os.path.join(HERE, "..", "power"))
from gen_cml import prbs7, pwl, NETDIR, UI  # noqa: E402
import gen_power as gp  # noqa: E402

PHASES = [-0.1, -0.03, 0.03, 0.1]
NBITS = 60
VLOCK = 0.79


def deck(design):
    bits = prbs7(NBITS)
    tstop = NBITS * UI
    lines, saves = [], []
    for k, ph in enumerate(PHASES):
        if design == "cml":
            lo, hi, tr = 1.03, 1.43, 200e-12
        else:
            lo, hi, tr = 0.0, 1.8, 80e-12
        # rising edge (mid-swing) at bit centre + ph*UI; ph > 0 = clock late
        td = 0.5 * UI + ph * UI - tr / 2
        pw = UI / 2 - tr
        lines.append(f"* offset {ph:+.2f} UI")
        lines.append(f"Vck{k} ck{k} 0 PULSE({lo} {hi} {td:.4e} {tr} {tr} {pw:.4e} {UI})")
        if design == "cml":
            lines.append(f"Vckb{k} ckb{k} 0 PULSE({hi} {lo} {td:.4e} {tr} {tr} {pw:.4e} {UI})")
            lines.append(f"xpd{k} vdd 0 dn{k} up{k} ck{k} ckb{k} dp dm vbias cml_pd")
        else:
            lines.append(f"xinv{k} vdd 0 ck{k} ckb{k} single_inverter")
            lines.append(f"xpd{k} vdd 0 dn{k} up{k} ck{k} dp ckb{k} dm vbias alexander_phase_detector")
        lines.append(f"xbg{k} 0 0 vdd vdd bn{k} vdd 0 bp{k} tiny_pll_bias_gen")
        lines.append(f"xcp{k} vdd vdd 0 0 vc{k} up{k} dn{k} bn{k} bp{k} tiny_pll_charge_pump")
        lines.append(f"Vvc{k} vc{k} 0 {VLOCK}")
        saves += [f"i(Vvc{k})", f"v(up{k})", f"v(dn{k})"]
    lets = "\n".join(f"  let icp{k} = -i(Vvc{k})" for k in range(len(PHASES)))
    names = " ".join(f"icp{k}" for k in range(len(PHASES)))
    return f"""* GENERATED by gen_u1.py -- do not edit.
* U1 ({design}): PD loop delay, open loop, offsets {' '.join(f'{p:+.2f}' for p in PHASES)} UI
* bits {''.join(map(str, bits))}
.lib {gp.PDK}/sky130A/libs.tech/ngspice/sky130.lib.spice tt
.include {NETDIR}/frozen.inc
.include {NETDIR}/cml_cells.inc
.options method=gear reltol=0.001
Vdd vdd 0 1.8
Vb vbias 0 0.9
Vd vd 0 PWL({pwl(bits, 0.15)})
Ep dp 0 vol='1.3 + v(vd)'
Em dm 0 vol='1.3 - v(vd)'
{chr(10).join(lines)}
.control
  save {' '.join(saves)}
  tran 5p {tstop:.4e}
{lets}
  set filetype=ascii
  write U1_{design}.raw {names}
.endc
.end
"""


def main():
    os.makedirs(os.path.join(HERE, "decks"), exist_ok=True)
    for d in ("frozen", "cml"):
        with open(os.path.join(HERE, "decks", f"U1_{d}.spice"), "w") as fh:
            fh.write(deck(d))
    print("wrote decks/U1_frozen.spice decks/U1_cml.spice")


if __name__ == "__main__":
    main()
