#!/usr/bin/env python3
"""U8: CML phase-detector characteristic (net pump charge vs clock offset) per corner.

    gen_u8.py        # writes decks/U8_<corner>.spice

U7 found the CML PD giving mixed up/down decisions at a fixed -0.03 UI offset
at sf/27C, sf/125C and ff/125C, where tt gives a clean single sign. Either the
PD's balance point has moved (benign: the loop tracks it as a static
sampling-phase offset) or decisions are random near the point (bad). Sweeping
the offset tells them apart: a clean sign flip at one offset is the former.
One transient per corner, eight PD + pump copies at the OFFSETS below; data
PRBS7 at CTLE levels (CM 1.3 V); ideal CML-level clock (1.03-1.43 V).
u8_analyze.py reports net charge per transition per offset.
Pure stdlib (../../../CLAUDE.md).
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "cml"))
sys.path.insert(0, os.path.join(HERE, "..", "power"))
sys.path.insert(0, os.path.join(HERE, "..", "pvt"))
from gen_cml import prbs7, pwl, NETDIR, UI  # noqa: E402
import gen_power as gp  # noqa: E402
from gen_pvt import corner_block  # noqa: E402

OFFSETS = [-0.15, -0.09, -0.05, -0.02, 0.01, 0.04, 0.08, 0.12]
CORNERS = [("tt", 27), ("sf", 27), ("sf", 125), ("ff", 125)]
NB = 30


def deck(mos, temp, cell="cml_pd"):
    bits = prbs7(NB + 20)[20:]
    tr = 200e-12
    pw = UI / 2 - tr
    L, names = [], []
    for k, ph in enumerate(OFFSETS):
        td = 0.5 * UI + ph * UI - tr / 2
        L += [f"* offset {ph:+.2f} UI",
              f"Vck{k} ck{k} 0 PULSE(1.03 1.43 {td:.4e} {tr} {tr} {pw:.4e} {UI})",
              f"Vckb{k} ckb{k} 0 PULSE(1.43 1.03 {td:.4e} {tr} {tr} {pw:.4e} {UI})",
              f"xpd{k} vdd 0 dn{k} up{k} ck{k} ckb{k} dp dm vbias {cell}",
              f"xbg{k} 0 0 vdd vdd bn{k} vdd 0 bp{k} tiny_pll_bias_gen",
              f"xcp{k} vdd vdd 0 0 vc{k} up{k} dn{k} bn{k} bp{k} tiny_pll_charge_pump",
              f"Vvc{k} vc{k} 0 0.79"]
        names.append(f"i{k}")
    lets = "\n".join(f"  let i{k} = -i(Vvc{k})" for k in range(len(OFFSETS)))
    return f"""* GENERATED by gen_u8.py -- do not edit.
* U8 ({mos} {temp}C, {cell}): PD characteristic, offsets {' '.join(f'{p:+.2f}' for p in OFFSETS)} UI
* bits {''.join(map(str, bits))}
{corner_block(mos, "typ", temp)}
.include {gp.PDK}/sky130A/libs.ref/sky130_fd_sc_hd/spice/sky130_fd_sc_hd.spice
.include {NETDIR}/frozen.inc
.include {NETDIR}/cml_cells.inc
.include {HERE}/cx_cells.inc
.options method=gear reltol=0.001
Vdd vdd 0 1.8
Vb vbias 0 0.9
Vd vd 0 PWL({pwl(bits, 0.15)})
Ep dp 0 vol='1.3 + v(vd)'
Em dm 0 vol='1.3 - v(vd)'
{chr(10).join(L)}
.control
  save {' '.join(f'i(Vvc{k})' for k in range(len(OFFSETS)))}
  tran 5p {NB * UI:.4e}
{lets}
  set filetype=ascii
  write U8{'' if cell == 'cml_pd' else '_' + cell.split('_')[-1]}_{mos}_{temp}C.raw {' '.join(names)}
.endc
.end
"""


if __name__ == "__main__":
    os.makedirs(os.path.join(HERE, "decks"), exist_ok=True)
    for m, t in CORNERS:
        with open(os.path.join(HERE, "decks", f"U8_{m}_{t}C.spice"), "w") as fh:
            fh.write(deck(m, t))
        # cx3: static-CMOS XORs, no level-shifted latch (cx_cells.inc)
        with open(os.path.join(HERE, "decks", f"U8_cx3_{m}_{t}C.spice"), "w") as fh:
            fh.write(deck(m, t, "cml_pd_cx3"))
    print("wrote " + " ".join(f"decks/U8_{m}_{t}C.spice" for m, t in CORNERS))
