#!/usr/bin/env python3
"""U4 (frozen PD) / U7 (CML PD): phase-detector behaviour across PVT.

    gen_u4.py        # writes decks/U4_<mos>.spice (frozen) and decks/U7_<mos>.spice (CML)

U7 runs the CML PD (cml_pd) the same way, clocked by an ideal CML-level clock
(1.03-1.43 V, the weakened diff_amp_inv's nominal output) -- it tests the PD's
own margin, not the buffer's, which would itself move with the corner.

U3 found that the frozen alexander_phase_detector's `up` (= Q2 xor B, both
switching on the same clock edge into a static XOR) glitches ~100 ps wide at
every decision, and that the glitch cancels ~61 % of each decision's charge at
tt/27C/1.8V. Glitch height is a gate-delay race, so the frozen loop's
effective gain should move with PVT. This measures how much.

Per deck: one MOS corner (R/C typical), temperatures -40/27/125 C unrolled
(each its own transient and rawfile); the tt deck also runs 1.62 V and
1.98 V at 27 C. Circuit as U3: ideal clock at -0.03 UI, frozen PD
(alex_probe.inc), real tiny_pll_charge_pump + bias_gen into an ideal 0.79 V
source, PRBS7 at CTLE levels (CM 1.3 V -- the CTLE's output CM itself moves
1.149-1.511 V over PVT, §C22, which this does not include).
u4_analyze.py reports the glitch and the cancelled fraction per run.
Pure stdlib (../../../CLAUDE.md).
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "cml"))
sys.path.insert(0, os.path.join(HERE, "..", "power"))
sys.path.insert(0, os.path.join(HERE, "..", "pvt"))
from gen_cml import prbs7, pwl, NETDIR, UI  # noqa: E402
import gen_power as gp  # noqa: E402
from gen_pvt import corner_block  # noqa: E402

MOS = ["tt", "ss", "ff", "sf", "fs"]
TEMPS = [-40, 27, 125]
NB = 30
PH = -0.03


def runs(mos):
    r = [(t, 1.8) for t in TEMPS]
    if mos == "tt":
        r += [(27, 1.62), (27, 1.98)]
    return r


def pd_lines(pd, td, tr, pw):
    if pd == "frozen":
        return "\n".join([
            f"Vck0 ck0 0 PULSE(0 1.8 {td:.4e} {tr} {tr} {pw:.4e} {UI})",
            "xinv0 vdd 0 ck0 ckb0 single_inverter",
            "xpd0 vdd 0 dn0 up0 ck0 dp ckb0 dm vbias bp0 bm0 q5p q5m q2p q2m alex_probe"])
    return "\n".join([
        f"Vck0 ck0 0 PULSE(1.03 1.43 {td:.4e} {tr} {tr} {pw:.4e} {UI})",
        f"Vckb0 ckb0 0 PULSE(1.43 1.03 {td:.4e} {tr} {tr} {pw:.4e} {UI})",
        "xpd0 vdd 0 dn0 up0 ck0 ckb0 dp dm vbias cml_pd"])


def deck(mos, pd="frozen"):
    bits = prbs7(NB + 20)[20:]
    tr = 80e-12 if pd == "frozen" else 200e-12
    td = 0.5 * UI + PH * UI - tr / 2
    pw = UI / 2 - tr
    ctl = []
    for t, v in runs(mos):
        tag = f"{mos}_{t}C_{v:.2f}V".replace(".", "p").replace("-", "m")
        pre = "U4" if pd == "frozen" else "U7"
        clkalter = (f"  alter Vck0 pulse = [ 0 {v} {td:.4e} {tr} {tr} {pw:.4e} {UI} ]"
                    if pd == "frozen" else "* (CML clock levels fixed)")
        ctl += [f"  option temp={t}",
                f"  alter Vdd dc={v}",
                clkalter,
                f"  tran 5p {NB * UI:.4e}",
                "  let i0 = -i(Vvc0)",
                "  set filetype=ascii",
                f"  write {pre}_{tag}.raw up0 dn0 i0",
                "  reset"]
    return f"""* GENERATED by gen_u4.py -- do not edit.
* {"U4" if pd == "frozen" else "U7"} ({mos}): {pd} PD vs PVT, offset {PH:+.2f} UI
* bits {''.join(map(str, bits))}
{corner_block(mos, "typ", 27)}
.include {gp.PDK}/sky130A/libs.ref/sky130_fd_sc_hd/spice/sky130_fd_sc_hd.spice
.include {NETDIR}/frozen.inc
.include {NETDIR}/cml_cells.inc
.include {HERE}/alex_probe.inc
.options method=gear reltol=0.001
Vdd vdd 0 1.8
Vb vbias 0 0.9
Vd vd 0 PWL({pwl(bits, 0.15)})
Ep dp 0 vol='1.3 + v(vd)'
Em dm 0 vol='1.3 - v(vd)'
{pd_lines(pd, td, tr, pw)}
xbg0 0 0 vdd vdd bn0 vdd 0 bpp0 tiny_pll_bias_gen
xcp0 vdd vdd 0 0 vc0 up0 dn0 bn0 bpp0 tiny_pll_charge_pump
Vvc0 vc0 0 0.79
.control
  save v(up0) v(dn0) i(Vvc0)
{chr(10).join(ctl)}
.endc
.end
"""


if __name__ == "__main__":
    os.makedirs(os.path.join(HERE, "decks"), exist_ok=True)
    for m in MOS:
        with open(os.path.join(HERE, "decks", f"U4_{m}.spice"), "w") as fh:
            fh.write(deck(m))
        with open(os.path.join(HERE, "decks", f"U7_{m}.spice"), "w") as fh:
            fh.write(deck(m, "cml"))
    print("wrote decks/U4_<corner>.spice and decks/U7_<corner>.spice for " + " ".join(MOS))
