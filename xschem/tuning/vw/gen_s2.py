#!/usr/bin/env python3
"""S2: the full CML chain with all three fixes -- cx3 PD, cml_bias (2a), scaled filter.

    gen_s2.py        # writes decks/S2_cx_ref.spice (S1-style: near lock, 1.5 us)

Topology = gen_cml's CDR_cml_dai with:
  * x3 = cml_pd_cx3 (cx_cells.inc: CML latches, static-CMOS XORs, no
    level-shifted latch) instead of cml_pd;
  * a cml_bias cell (bias/cml_bias.inc) making vbn, which feeds the PD and the
    two recovered-clock cml2cmos converters instead of the vbias pin (the CTLE
    keeps vbias; the clock buffer keeps its vtail source);
  * the scaled loop filter (frozen_scaled.inc: R 33.2 kohm, C1 291 fF,
    C2 43.5 fF).
Flattened by ../power/gen_power.py like every chain deck here, so every leaf
cell (cml_bias included) has its own metered supply. Same analysis as S1:
v1_analyze.py on the .dat, ../c27_analyze.py on the chain rawfile.
Pure stdlib (../../../CLAUDE.md).
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "cml"))
sys.path.insert(0, os.path.join(HERE, "..", "power"))
import gen_cml as gc  # noqa: E402
import gen_power as gp  # noqa: E402

TOPO = os.path.join(HERE, "cx_top.inc")


def topology():
    t = gc.cdr_cml("dai")
    t = t.replace("CDR_cml_dai", "CDR_cml_cx").replace("top_cml_dai", "top_cml_cx")
    old_pd = "x3 Vdd Vss net3 net2 ck ckb vin+ vin- vbias cml_pd"
    assert old_pd in t
    t = t.replace(old_pd, "xref Vdd Vss vbn cml_bias\n"
                          "x3 Vdd Vss net3 net2 ck ckb vin+ vin- vbn cml_pd_cx3")
    for conv in ("x11 rclk+ ck ckb Vdd Vss vbias cml2cmos", "x12 rclk- ckb ck Vdd Vss vbias cml2cmos"):
        assert conv in t
        t = t.replace(conv, conv.replace(" vbias ", " vbn "))
    return gc.RING_CORE + t


def main():
    with open(TOPO, "w") as fh:
        fh.write("* GENERATED by gen_s2.py -- CML CDR with cx3 PD and cml_bias\n" + topology())
    netlist = gp.netlist_fresh()
    subs = gp.parse(netlist)
    for p in (os.path.join(gc.NETDIR, "cml_cells.inc"), os.path.join(HERE, "cx_cells.inc"),
              os.path.join(HERE, "bias", "cml_bias.inc"), TOPO):
        subs.update(gp.parse(p))
    gp.EXPAND.update({"cml_pd_cx3"})
    text, ndev = gc.deck_chain(subs, "cx", 0.85, tstop=1500)
    # includes: our cells, the scaled filter in place of the frozen one
    frozen = f".include {gc.NETDIR}/frozen.inc"
    assert frozen in text
    text = text.replace(frozen, f".include {HERE}/frozen_scaled.inc")
    text = text.replace(f".include {gc.NETDIR}/cml_top.inc",
                        f".include {HERE}/cx_cells.inc\n.include {HERE}/bias/cml_bias.inc\n.include {TOPO}")
    text = text.replace("e2e_prbs3u.inc", "e2e_prbs6u.inc")
    # S1 conditions: start near lock, measure 0.5-1.5 us, dump like V1/S1
    text = text.replace(".ic v(x2_x20.nrc)=0",
                        ".ic v(x2_x20.nrc)=0 v(x2_net1)=0.785 v(x2_x2.cap_plus)=0.785")
    text = text.replace("v(x2_net2) v(x2_net3)\n",
                        "v(x2_net2) v(x2_net3) v(x2_x2.cap_plus) v(rclk_p) v(eq_p) v(eq_m)\n", 1)
    text = text.replace("  set filetype=ascii\n  wrdata C3_cx_vctrl.dat v(x2_net1)",
                        "  let rclkp = v(rclk_p)\n  let coutp = v(eq_p)\n  let coutm = v(eq_m)\n"
                        "  set filetype=ascii\n  write S2_cx_ref_chain.raw rclkp coutp coutm\n"
                        "  wrdata S2_cx_ref.dat v(x2_net1) v(x2_x2.cap_plus) v(x2_net2) v(x2_net3) v(rclk_p)")
    assert "S2_cx_ref.dat" in text and "frozen_scaled.inc" in text and "x2_x2.cap_plus)=0.785" in text
    text = text.replace("* C3 (cx,", "* S2 (cx3 PD + cml_bias + scaled filter,", 1)
    with open(os.path.join(HERE, "decks", "S2_cx_ref.spice"), "w") as fh:
        fh.write(text)
    print(f"wrote decks/S2_cx_ref.spice ({ndev} devices metered)")


if __name__ == "__main__":
    main()
